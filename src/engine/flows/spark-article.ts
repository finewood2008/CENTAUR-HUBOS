// ---------------------------------------------------------------------------
// 类型定义
// ---------------------------------------------------------------------------

/** 步骤类型：ai = AI 生成, confirm = 卡片确认 */
export type StepType = 'ai' | 'confirm';

/** 单个流程步骤 */
export interface FlowStep {
  id: string;
  type: StepType;
  /** AI 步骤的 system prompt */
  prompt?: string;
  /** confirm 步骤对应的卡片模板名 */
  cardTemplate?: string;
  /** confirm 步骤使用的数据映射函数名 */
  dataMapper?: string;
  /** 下一步的 step id，undefined 表示流程结束 */
  next?: string;
}

/** 完整流程定义 */
export interface FlowDefinition {
  id: string;
  name: string;
  description: string;
  /** 所属员工 ID */
  employeeId: string;
  /** 入口步骤 ID */
  entryStep: string;
  /** 步骤映射表 */
  steps: Record<string, FlowStep>;
}

